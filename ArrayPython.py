# Array
Daftar_Keluarga = ["Andi", "Budi", "Elma", "Jenny"]
print(Daftar_Keluarga)
print(Daftar_Keluarga[0])  # Andi
print(Daftar_Keluarga[1:3])  # Budi, Jenny
print(Daftar_Keluarga[:2])  # Andi, Budi
print(Daftar_Keluarga[1:])  # Budi, Elmma, Jenny

# Array dalam Array
